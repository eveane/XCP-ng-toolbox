fn gib(bytes: u64) -> String {
    if bytes == 0 {
        return "0".to_string();
    }
    format!("{:.2} GiB", bytes as f64 / 1024.0 / 1024.0 / 1024.0)
}

fn mib(bytes: u64) -> String {
    format!("{:.0} MiB", bytes as f64 / 1024.0 / 1024.0)
}

/// Format a unix timestamp as "YYYY-MM-DD HH:MM UTC" (no external crates:
/// inverse civil-from-days conversion, Howard Hinnant's algorithm).
fn utc_timestamp(epoch: u64) -> String {
    let days = epoch / 86400;
    let secs = epoch % 86400;
    let z = days as i64 + 719468;
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = z - era * 146097;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    format!(
        "{y:04}-{m:02}-{d:02} {:02}:{:02} UTC",
        secs / 3600,
        (secs % 3600) / 60
    )
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Section {
    All,
    Pool,
    Hosts,
    SRs,
    VMs,
    VDIs,
    VBDs,
    VIFs,
    PBDs,
    PIFs,
    Network,
    Storage,
    Anomalies,
}

impl Section {
    pub fn parse(s: &str) -> Option<Section> {
        Some(match s.to_lowercase().as_str() {
            "all" | "" => Section::All,
            "pool" => Section::Pool,
            "hosts" | "host" => Section::Hosts,
            "srs" | "sr" => Section::SRs,
            "vms" | "vm" => Section::VMs,
            "vdis" | "vdi" => Section::VDIs,
            "vbds" | "vbd" => Section::VBDs,
            "vifs" | "vif" => Section::VIFs,
            "pbds" | "pbd" => Section::PBDs,
            "pifs" | "pif" => Section::PIFs,
            "network" | "networks" | "net" => Section::Network,
            "storage" => Section::Storage,
            "anomalies" | "anomaly" | "attention" | "findings" => Section::Anomalies,
            _ => None?,
        })
    }

    /// Parse a comma-separated list of sections, e.g. "pool,storage".
    /// Returns Err with the offending name when one entry is unknown.
    pub fn parse_list(s: &str) -> Result<Vec<Section>, String> {
        let mut out = Vec::new();
        for part in s.split(',').map(str::trim).filter(|p| !p.is_empty()) {
            match Section::parse(part) {
                Some(sec) => out.push(sec),
                None => return Err(part.to_string()),
            }
        }
        if out.is_empty() {
            out.push(Section::All);
        }
        Ok(out)
    }
}

#[allow(dead_code)]
pub fn render_text(r: &BundleReport) -> String {
    render_sections(r, &[Section::All])
}

pub fn render_sections(r: &BundleReport, sections: &[Section]) -> String {
    let mut out = String::new();
    let has = |sec: Section| sections.iter().any(|s| *s == sec);
    let show = |want: Section| {
        has(Section::All)
            || has(want)
            || (has(Section::Network)
                && (want == Section::PIFs || want == Section::VIFs)
                && !has(Section::PIFs)
                && !has(Section::VIFs))
            || (has(Section::Storage)
                && (want == Section::SRs || want == Section::VDIs || want == Section::PBDs)
                && !has(want))
            || ((has(Section::SRs) || has(Section::VDIs) || has(Section::PBDs))
                && want == Section::Storage)
            // pifs/vifs alone: like srs -> Storage, render the merged Network
            || ((has(Section::PIFs) || has(Section::VIFs))
                && want == Section::Network)
    };
    if show(Section::Pool) {
        render_pool(r, &mut out);
    }
    if show(Section::Hosts) {
        render_hosts(r, &mut out);
    }
    if show(Section::VMs) {
        render_vms(r, &mut out);
    }
    if show(Section::Network) {
        render_network(r, &mut out);
    }
    if show(Section::Storage) {
        render_storage(r, &mut out);
    }
    if show(Section::VBDs) {
        render_vbds(r, &mut out);
    }
    // The anomalies section is opt-in only: it is never part of Section::All.
    if has(Section::Anomalies) && !has(Section::All) {
        render_anomalies(r, &mut out);
    }
    if has(Section::All) {
        for w in &r.warnings {
            let _ = writeln!(out, "WARNING: {w}");
        }
    }
    out
}

fn render_pool(r: &BundleReport, out: &mut String) {
    let _ = writeln!(out, "=== Status report analysis: {} ===", r.bundle_path);
    let _ = writeln!(out, "generated by xcp-bundle-analyzer {VERSION}");
    if !r.bundle_origin_host.is_empty() {
        let _ = writeln!(out, "bundle collected from host: {}", r.bundle_origin_host);
    }
    let _ = writeln!(
        out,
        "Pool: {} (uuid {}), master: {}",
        r.pool.name, r.pool.uuid, r.pool.master
    );
    let _ = writeln!(
        out,
        "Hosts: {}   VMs: {} running / {} total   Networks: {}",
        r.pool.host_count, r.pool.vm_running, r.pool.vm_total, r.networks
    );
    let _ = writeln!(
        out,
        "SR storage: {} total, {} used   VDIs total size: {}",
        gib(r.pool.sr_total_size_bytes),
        gib(r.pool.sr_total_used_bytes),
        gib(r.pool.vdi_total_size_bytes)
    );
}

fn render_hosts(r: &BundleReport, out: &mut String) {
    let _ = writeln!(out, "\n--- HOSTS ({}) ---", r.hosts.len());
    for h in &r.hosts {
        let _ = writeln!(
            out,
            "{} [{}] {}{}{}",
            h.hostname,
            h.uuid,
            if h.enabled { "enabled" } else { "disabled" },            if h.is_master { "  <== POOL MASTER" } else { "" },
            if h.is_bundle_origin { "  <<< THIS BUNDLE" } else { "" }
        );
        let _ = writeln!(
            out,
            "  address: {}   state: {}   ref: {}",
            h.address, h.power_state, h.opaque_ref
        );
        let _ = writeln!(
            out,
            "  product: {}   xen: {}   kernel: {}",
            h.product_version, h.xen_version, h.kernel_version
        );
        let _ = writeln!(
            out,
            "  cpu: {} x {} ({} sockets, {} cores/socket)",
            h.cpu_count, h.cpu_model, h.sockets, h.cores_per_socket
        );
        let _ = writeln!(
            out,
            "  memory: {} total / {} free{}   dom0: {} (live: {})",
            gib(h.memory_total_bytes),
            gib(h.memory_free_bytes),
            if h.mem_free_stale { " (free memory unknown/unavailable in dump)" } else { "" },
            h.dom0_memory_config_mib
                .map(|m| format!("{m} MiB"))
                .or_else(|| h.dom0_memory_live_bytes.map(|b| mib(b)))
                .unwrap_or_else(|| "n/a".into()),
            h.dom0_memory_live_bytes
                .map(|b| mib(b))
                .unwrap_or_else(|| "n/a".into())
        );
        if let (Some(up), Some(boot)) = (h.uptime_seconds, h.boot_time) {
            let days = up / 86400;
            let hrs = (up % 86400) / 3600;
            let mins = (up % 3600) / 60;
            let _ = writeln!(
                out,
                "  uptime: {days}d {hrs}h {mins}m (booted at {}, unix {boot})",
                utc_timestamp(boot)
            );
        } else if let Some(boot) = h.boot_time {
            let _ = writeln!(
                out,
                "  boot time: {} (unix {boot}, dump time unknown so no uptime)",
                utc_timestamp(boot)
            );
        }
        let _ = writeln!(
            out,
            "  VMs: {} running / {} resident   vCPUs in use: {}",
            h.vms_running, h.vms_resident, h.vcpus_in_use
        );
        if let Some(interval) = h.auto_scan_interval {
            let _ = writeln!(
                out,
                "  *** auto-scan-interval: {interval}s ({}rescans SRs every {interval}s; only effective while this host is the master — if the master role moves to a host without the setting, rescans revert to the default: every 30s, or every 5min for linstor/xostor) ***",
                if h.is_master { "" } else { "not the master right now; " }
            );
        } else if h.is_master {
            let _ = writeln!(
                out,
                "  *** auto-scan-interval: not set on this master; rescans run at the default (every 30s, or every 5min for linstor/xostor) ***"
            );
        }
        let _ = writeln!(out, "  PBDs: {}   PIFs: {}", h.pbd_count, h.pif_count);
    }
}

fn render_storage(r: &BundleReport, out: &mut String) {
    let _ = writeln!(out, "\n=== STORAGE ===");
    let vdi_base = r.vdis.iter().filter(|d| !d.is_snapshot).count();
    let vdi_snap = r.vdis.iter().filter(|d| d.is_snapshot).count();
    let vdi_orphan = r.vdis.iter().filter(|d| d.orphaned).count();
    let _ = writeln!(
        out,
        "SRs: {}   VDIs: {} ({} base, {} snapshots, {} orphaned)   PBDs: {}   inconsistencies: {}",
        r.srs.len(),
        r.vdis.len(),
        vdi_base,
        vdi_snap,
        vdi_orphan,
        r.pbds.len(),
        r.pbd_inconsistencies.len()
    );

    // Host adapters (FC HBAs, iSCSI targets, NFS servers)
    let any_adapter = r.hosts.iter().any(|h| !h.storage_adapters.is_empty());
    if any_adapter {
        let _ = writeln!(out, "\n--- HOST STORAGE ADAPTERS ---");
        for h in &r.hosts {
            if h.storage_adapters.is_empty() {
                continue;
            }
            let _ = writeln!(out, "\n  host: {} ({} adapters)", h.hostname, h.storage_adapters.len());
            for a in &h.storage_adapters {
                let _ = writeln!(
                    out,
                    "    [{}] {} {}",
                    a.kind, a.id, a.description
                );
            }
        }
    }

    {
        let mut inner = String::new();
        render_srs_body(r, &mut inner);
        render_vdis_body(r, &mut inner);
        render_pbds_body(r, &mut inner);
        // strip the duplicated outer headers, keep sub-sections
        out.push_str(&inner);
    }
}

fn render_srs_body(r: &BundleReport, out: &mut String) {
    let _ = writeln!(out, "\n--- STORAGE REPOSITORIES ({}) ---", r.srs.len());
    for s in &r.srs {
        let _ = writeln!(
            out,
            "{} [{}] type={} category={} shared={} size={} used={} PBDs={} VDIs={}",
            s.name,
            s.uuid,
            s.sr_type,
            s.category,
            s.shared,
            gib(s.size_bytes),
            gib(s.used_bytes),
            s.pbd_count,
            s.vdi_count
        );
        if let Some(interval) = s.auto_scan_interval {
            let _ = writeln!(
                out,
                "  *** auto-scan-interval: {interval}s (SR is rescanned automatically every {interval}s) ***"
            );
        }
        if !s.hosts.is_empty() {
            let _ = writeln!(out, "  attached to hosts: {}", s.hosts.join(", "));
        }
        if !s.device_config.is_empty() {
            let _ = writeln!(out, "  device-config:");
            for (k, v) in &s.device_config {
                let _ = writeln!(out, "    {k} = {v}");
            }
        }
        if !s.other_config.is_empty() {
            let _ = writeln!(out, "  other-config:");
            for (k, v) in &s.other_config {
                let _ = writeln!(out, "    {k} = {v}");
            }
        }
        if !s.multipath.is_empty() {
            let _ = writeln!(out, "  multipath:");
            for m in &s.multipath {
                let _ = writeln!(
                    out,
                    "    host={} paths={} ({})",
                    m.host,
                    m.paths.map(|p| p.to_string()).unwrap_or_else(|| "?".into()),
                    m.raw
                );
            }
            if s.multipath_mismatch {
                let _ = writeln!(
                    out,
                    "  *** MULTIPATH PATH COUNT MISMATCH between hosts ***"
                );
            }
        }
    }
}

fn render_vms(r: &BundleReport, out: &mut String) {
    let real_vms: Vec<_> = r
        .vms
        .iter()
        .filter(|v| !v.is_template && !v.is_snapshot && !v.is_vmss_snapshot && !v.is_control_domain)
        .collect();
    let mut templates: Vec<_> = r
        .vms
        .iter()
        .filter(|v| v.is_template)
        .collect();
    let mut snapshots: Vec<_> = r
        .vms
        .iter()
        .filter(|v| v.is_snapshot || v.is_vmss_snapshot)
        .collect();
    templates.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));
    snapshots.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));

    // Group real VMs per resident host, alphabetical within each group.
    let mut by_host: BTreeMap<String, Vec<&VmReport>> = BTreeMap::new();
    for v in &real_vms {
        by_host
            .entry(if v.resident_host.is_empty() { "(not running)".to_string() } else { v.resident_host.clone() })
            .or_default()
            .push(v);
    }
    for (_, group) in by_host.iter_mut() {
        group.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));
    }

    let _ = writeln!(out, "\n--- VIRTUAL MACHINES ({}) ---", real_vms.len());
    for (host, group) in &by_host {
        let running = group.iter().filter(|v| v.power_state == "Running").count();
        let vcpus: u64 = group
            .iter()
            .filter(|v| v.power_state == "Running")
            .map(|v| v.vcpus_at_startup.max(v.vcpus_max))
            .sum();
        let _ = writeln!(
            out,
            "\n  host: {} ({} running, {} vCPUs in use)",
            host,
            running,
            vcpus
        );
        for v in group {
            let _ = writeln!(
                out,
                "    {} [{}] {} vCPUs={} mem={} VIFs={} VBDs={}",
                v.name,
                v.uuid,
                v.power_state,
                v.vcpus_max,
                mib(v.memory_dynamic_max_bytes),
                v.vif_count,
                v.vbd_count
            );
            if !v.os_name.is_empty() {
                let _ = writeln!(out, "        os: {}", v.os_name);
            }
        }
    }

    let _ = writeln!(out, "\n--- TEMPLATES ({}) ---", templates.len());
    for v in &templates {
        let _ = writeln!(
            out,
            "{} [{}] {} vCPUs={} mem={}",
            v.name,
            v.uuid,
            if v.is_default_template { "(default)" } else { "" },
            v.vcpus_max,
            mib(v.memory_static_max_bytes)
        );
    }

    let _ = writeln!(out, "\n--- SNAPSHOTS ({}) ---", snapshots.len());
    for v in &snapshots {
        let _ = writeln!(
            out,
            "{} [{}] vCPUs={} mem={}",
            v.name,
            v.uuid,
            v.vcpus_max,
            mib(v.memory_static_max_bytes)
        );
    }
}

fn render_vdis_body(r: &BundleReport, out: &mut String) {
    // HA statefiles listed separately, on top
    let statefiles: Vec<_> = r.vdis.iter().filter(|d| d.is_ha_statefile).collect();
    let mut normal: Vec<_> = r.vdis.iter().filter(|d| !d.is_ha_statefile).collect();
    normal.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));

    let vdi_base = r.vdis.iter().filter(|d| !d.is_snapshot).count();
    let vdi_snap = r.vdis.iter().filter(|d| d.is_snapshot).count();
    let vdi_orphan = r.vdis.iter().filter(|d| d.orphaned).count();
    let _ = writeln!(
        out,
        "\n--- VDIs ({}) — {} base, {} snapshots, {} orphaned ---",
        r.vdis.len(),
        vdi_base,
        vdi_snap,
        vdi_orphan
    );
    if !statefiles.is_empty() {
        let _ = writeln!(out, "\n  *** HA STATEFILES ({}) ***", statefiles.len());
        for d in &statefiles {
            let _ = writeln!(
                out,
                "  {} [{}] sr={} size={}",
                d.name, d.uuid, d.sr, gib(d.size_bytes)
            );
        }
    }

    // group per SR, alphabetical inside each group
    let mut by_sr: BTreeMap<String, Vec<&VdiReport>> = BTreeMap::new();
    for d in &normal {
        let key = if d.sr.is_empty() { "(no SR)".to_string() } else { d.sr.clone() };
        by_sr.entry(key).or_default().push(d);
    }
    for (sr, group) in &by_sr {
        let total: u64 = group.iter().map(|d| d.size_bytes).sum();
        let _ = writeln!(out, "\n  SR: {} ({} VDIs, {} total)", sr, group.len(), gib(total));
        for d in group {
            let mut flags = String::new();
            if d.is_snapshot {
                flags.push_str(" SNAPSHOT");
            }
            if d.has_snapshots {
                flags.push_str(" HAS-SNAPSHOTS");
            }
            if d.broken_parent {
                flags.push_str(" *** BROKEN PARENT (snapshot_of points to a missing VDI) ***");
            }
            if d.orphaned {
                flags.push_str(" ORPHANED (not attached to any VM)");
            }
            let _ = writeln!(
                out,
                "    {} [{}] type={} size={}{}",
                d.name, d.uuid, d.vdi_type, gib(d.size_bytes), flags
            );
        }
    }
}

fn render_vbds(r: &BundleReport, out: &mut String) {
    let cds_attached = r
        .vbds
        .iter()
        .filter(|b| b.vbd_type == "CD" && b.attached)
        .count();
    // Group per VM UUID (names are not unique), devices sorted inside each
    // group; the groups themselves are ordered by VM name.
    let mut by_vm: BTreeMap<String, Vec<&VbdReport>> = BTreeMap::new();
    for b in &r.vbds {
        let key = if b.vm_uuid.is_empty() {
            format!("(no VM)|{}", b.vm)
        } else {
            b.vm_uuid.clone()
        };
        by_vm.entry(key).or_default().push(b);
    }
    let mut groups: Vec<(&String, &mut Vec<&VbdReport>)> = by_vm.iter_mut().collect();
    for (_, g) in groups.iter_mut() {
        g.sort_by(|a, b| a.device.to_lowercase().cmp(&b.device.to_lowercase()));
    }
    groups.sort_by(|(_, a), (_, b)| {
        let an = a.first().map(|b| b.vm.to_lowercase()).unwrap_or_default();
        let bn = b.first().map(|b| b.vm.to_lowercase()).unwrap_or_default();
        an.cmp(&bn)
    });
    let _ = writeln!(out, "\n--- VBDs ({}) ---", r.vbds.len());
    let _ = writeln!(out, "  CD devices attached: {}", cds_attached);
    for (key, group) in &groups {
        let b = group[0];
        let label = if b.vm.is_empty() && b.vm_uuid.is_empty() {
            "(no VM)".to_string()
        } else {
            format!("{} - {}", b.vm, b.vm_uuid)
        };
        let _ = if key.starts_with("(no VM)|") { writeln!(out, "\n  vm: {}", b.vm) } else { writeln!(out, "\n  vm: {}", label) };
        for b in group.iter() {
        let vdi_short: String = b.vdi_uuid.chars().take(8).collect();
        let _ = writeln!(
            out,
            "    dev={} vdi={} [{}] type={} mode={} attached={} bootable={} uuid={}",
            b.device,
            b.vdi,
            vdi_short,
            b.vbd_type,
            b.mode,
            b.attached,
            b.bootable,
            b.uuid
        );
        }
    }
}

fn render_pbds_body(r: &BundleReport, out: &mut String) {
    let _ = writeln!(out, "\n--- PBDs ({}) ---", r.pbds.len());

    // inconsistencies on top
    if !r.pbd_inconsistencies.is_empty() {
        let _ = writeln!(out, "\n  *** PBD INCONSISTENCIES ({}) ***", r.pbd_inconsistencies.len());
        for inc in &r.pbd_inconsistencies {
            let _ = writeln!(
                out,
                "  [{}] {} [{}] on SR {}: {}",
                inc.kind, inc.sr, inc.sr_uuid, inc.sr, inc.detail
            );
        }
    }

    // group per SR
    let mut by_sr: BTreeMap<String, Vec<&PbdReport>> = BTreeMap::new();
    for p in &r.pbds {
        by_sr.entry(p.sr.clone()).or_default().push(p);
    }
    for (sr, group) in &by_sr {
        let shared = group.iter().any(|p| p.sr_shared);
        let _ = writeln!(
            out,
            "\n  SR: {}{} ({} PBDs)",
            sr,
            if shared { " [shared]" } else { " [local]" },
            group.len()
        );
        for p in group {
            let _ = writeln!(
                out,
                "    host={} attached={} uuid={} formats={}",
                p.host,
                p.attached,
                p.uuid,
                if p.preferred_formats.is_empty() { "-".to_string() } else { p.preferred_formats.join(" > ") }
            );
        }
    }
}

fn render_network(r: &BundleReport, out: &mut String) {
    let _ = writeln!(out, "\n=== NETWORK ===");
    // short summary header
    let bonds = r.pifs.iter().filter(|p| p.is_bond_master).count();
    let nbd_nets = r.network_details.iter().filter(|n| n.is_nbd).count();
    let _ = writeln!(
        out,
        "networks: {}   PIFs: {}   VIFs: {}   bonds: {}   NBD networks: {}",
        r.networks,
        r.pifs.len(),
        r.vifs.len(),
        bonds,
        nbd_nets
    );
    // Migration / backup networks highlighted on top
    let mig = r.network_details.iter().find(|n| n.is_migration);
    if let Some(n) = mig {
        let _ = writeln!(out, "  *** LIVE MIGRATION NETWORK: {} [{}] bridge={} mtu={} ***", n.name, n.uuid, n.bridge, n.mtu);
    }
    let bak = r.network_details.iter().find(|n| n.is_backup);
    if let Some(n) = bak {
        let _ = writeln!(out, "  *** BACKUP NETWORK: {} [{}] bridge={} mtu={} ***", n.name, n.uuid, n.bridge, n.mtu);
    }
    if nbd_nets > 0 {
        let _ = writeln!(out, "  *** NBD: {} network(s) dedicated to Network Block Device traffic ***", nbd_nets);
        for n in r.network_details.iter().filter(|n| n.is_nbd) {
            let _ = writeln!(
                out,
                "      {} [{}] bridge={} mtu={} purposes={}",
                n.name, n.uuid, n.bridge, n.mtu, n.purposes.join(", ")
            );
        }
    }

    // PIFs grouped per host
    let _ = writeln!(out, "\n--- PIFs ({}) ---", r.pifs.len());
    let mut by_host: BTreeMap<String, Vec<&PifReport>> = BTreeMap::new();
    for p in &r.pifs {
        by_host
            .entry(if p.host.is_empty() { "(no host)".to_string() } else { p.host.clone() })
            .or_default()
            .push(p);
    }
    for (host, group) in &by_host {
        let mut group = group.clone();
        group.sort_by(|a, b| a.device.to_lowercase().cmp(&b.device.to_lowercase()));
        let mgmt = group.iter().filter(|p| p.management).count();
        let _ = writeln!(out, "\n  host: {} ({} PIFs, {} management)", host, group.len(), mgmt);
        for p in &group {
            let speed = p
                .speed
                .map(|s| if s >= 65535 { "-".to_string() } else { format!("{s} Mb/s") })
                .unwrap_or_else(|| "-".into());
            let mut extra = String::new();
            if p.is_bond_master {
                extra.push_str(&format!(" BOND({})", p.bond_members.join("+")));
            }
            if !p.device_name.is_empty() {
                extra.push_str(&format!(" [{} {}]", p.vendor_name, p.device_name));
            }
            if !p.pci_bus_path.is_empty() {
                extra.push_str(&format!(" pci={}", p.pci_bus_path));
            }
            let _ = writeln!(
                out,
                "    dev={} ip={} net={} mac={} vlan={} mgmt={} attached={} speed={}{}",
                p.device,
                p.address,
                p.network,
                p.mac,
                p.vlan.map(|v| v.to_string()).unwrap_or_else(|| "-".into()),
                p.management,
                p.attached,
                speed,
                extra
            );
        }
    }

    // VIFs sorted per VM
    let _ = writeln!(out, "\n--- VIFs ({}) ---", r.vifs.len());
    // Group per VM UUID (names are not unique), devices sorted inside each
    // group; the groups themselves are ordered by VM name.
    let mut by_vm: BTreeMap<String, Vec<&VifReport>> = BTreeMap::new();
    for v in &r.vifs {
        let key = if v.vm_uuid.is_empty() {
            format!("(no VM)|{}", v.vm)
        } else {
            v.vm_uuid.clone()
        };
        by_vm.entry(key).or_default().push(v);
    }
    let mut groups: Vec<(&String, &mut Vec<&VifReport>)> = by_vm.iter_mut().collect();
    for (_, g) in groups.iter_mut() {
        g.sort_by(|a, b| a.device.to_lowercase().cmp(&b.device.to_lowercase()));
    }
    groups.sort_by(|(_, a), (_, b)| {
        let an = a.first().map(|v| v.vm.to_lowercase()).unwrap_or_default();
        let bn = b.first().map(|v| v.vm.to_lowercase()).unwrap_or_default();
        an.cmp(&bn)
    });
    for (_key, group) in &groups {
        let v = group[0];
        let label = if v.vm.is_empty() && v.vm_uuid.is_empty() {
            "(no VM)".to_string()
        } else {
            format!("{} - {}", v.vm, v.vm_uuid)
        };
        let _ = writeln!(out, "\n  vm: {}", label);
        for v in group.iter() {
        let _ = writeln!(
            out,
            "    dev={} mac={} net={} attached={}",
            v.device, v.mac, v.network, v.attached
        );
        }
    }
}

fn print_anomalies_header(out: &mut String, count: usize) {
    let _ = writeln!(
        out,
        "\n=== SETTINGS NEEDING ATTENTION ({}) ===",
        count
    );
    let _ = writeln!(
        out,
        "Heuristic findings: each entry is probably abnormal or worth reviewing, but not necessarily a fault."
    );
}

/// Merge per-bundle reports (dedup by uuid) into one report on which the
/// pool-wide anomaly checks can run.
fn merge_for_anomalies(c: &ConsolidatedReport) -> BundleReport {
    let mut merged = c
        .bundles
        .first()
        .cloned()
        .unwrap_or_default();
    merged.pool.host_count = c.hosts.len();
    merged.hosts = c.hosts.clone();
    merged.srs = c.srs.clone();
    merged.vdis.clear();
    merged.vbds.clear();
    merged.pbd_inconsistencies.clear();
    let mut seen_vdi = std::collections::BTreeSet::new();
    let mut seen_vbd = std::collections::BTreeSet::new();
    let mut seen_inc = std::collections::BTreeSet::new();
    for b in &c.bundles {
        for d in &b.vdis {
            if seen_vdi.insert(d.uuid.clone()) {
                merged.vdis.push(d.clone());
            }
        }
        for v in &b.vbds {
            if seen_vbd.insert(v.uuid.clone()) {
                merged.vbds.push(v.clone());
            }
        }
        for i in &b.pbd_inconsistencies {
            if seen_inc.insert(format!("{}|{}", i.sr_uuid, i.detail)) {
                merged.pbd_inconsistencies.push(i.clone());
            }
        }
    }
    merged
}

/// Anomalies-only view of a consolidated (multi-bundle) pool report.
pub fn render_consolidated_anomalies(c: &ConsolidatedReport) -> String {
    let merged = merge_for_anomalies(c);
    let anomalies = crate::report::compute_anomalies(&merged);
    let mut out = String::new();
    print_anomalies_header(&mut out, anomalies.len());
    if anomalies.is_empty() {
        let _ = writeln!(out, "nothing abnormal detected");
    } else {
        for a in &anomalies {
            let _ = writeln!(
                out,
                "  [{}] {}{}",
                if a.severity == "warning" { "PROBABLY ABNORMAL" } else { "review" },
                if a.subject.is_empty() { String::new() } else { format!("{}: ", a.subject) },
                a.detail
            );
        }
    }
    out
}

fn render_anomalies(r: &BundleReport, out: &mut String) {
    let _ = writeln!(
        out,
        "\n=== SETTINGS NEEDING ATTENTION ({}) ===",
        r.anomalies.len()
    );
    let _ = writeln!(
        out,
        "Heuristic findings: each entry is probably abnormal or worth reviewing, but not necessarily a fault."
    );
    if r.anomalies.is_empty() {
        let _ = writeln!(out, "nothing abnormal detected");
        return;
    }
    let mut by_category: BTreeMap<String, Vec<&crate::report::Anomaly>> = BTreeMap::new();
    for a in &r.anomalies {
        by_category.entry(a.category.clone()).or_default().push(a);
    }
    for (category, group) in &by_category {
        let _ = writeln!(out, "\n--- {} ({}) ---", category, group.len());
        for a in group {
            let _ = writeln!(
                out,
                "  [{}] {}{}",
                if a.severity == "warning" { "PROBABLY ABNORMAL" } else { "review" },
                if a.subject.is_empty() { String::new() } else { format!("{}: ", a.subject) },
                a.detail
            );
        }
    }
}

pub fn render_consolidated_text(c: &ConsolidatedReport) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "=== Consolidated pool view ({} bundles) ===", c.bundles.len());
    let _ = writeln!(out, "generated by xcp-bundle-analyzer {VERSION}");
    let _ = writeln!(
        out,
        "Pool: {} (uuid {}), master: {}",
        c.pool.name, c.pool.uuid, c.pool.master
    );
    let _ = writeln!(
        out,
        "Hosts: {}   VMs: {} running / {} total",
        c.pool.host_count, c.pool.vm_running, c.pool.vm_total
    );
    let _ = writeln!(
        out,
        "SR storage: {} total, {} used",
        gib(c.pool.sr_total_size_bytes),
        gib(c.pool.sr_total_used_bytes)
    );
    for b in &c.bundles {
        let _ = writeln!(out, "\n### bundle: {}", b.bundle_path);
        if !b.bundle_origin_host.is_empty() {
            let _ = writeln!(out, "    collected from: {}", b.bundle_origin_host);
        }
        let _ = writeln!(
            out,
            "    hosts: {}, VMs running: {}/{}",
            b.pool.host_count, b.pool.vm_running, b.pool.vm_total
        );
    }
    let _ = writeln!(out, "\n--- POOL HOSTS ({} unique) ---", c.hosts.len());
    for h in &c.hosts {
        let _ = writeln!(
            out,
            "{} [{}] product={} xen={} mem={} dom0={} PBDs={}",
            h.hostname,
            h.uuid,
            h.product_version,
            h.xen_version,
            gib(h.memory_total_bytes),
            h.dom0_memory_config_mib
                .map(|m| format!("{m} MiB"))
                .unwrap_or_else(|| "n/a".into()),
            h.pbd_count
        );
    }
    // Anomalies across the consolidated view: merge the per-bundle reports
    // (dedup by uuid) and recompute the pool-wide checks on merged data.
    if !c.bundles.is_empty() {
        let merged = merge_for_anomalies(c);
        let anomalies = crate::report::compute_anomalies(&merged);
        print_anomalies_header(&mut out, anomalies.len());
        if anomalies.is_empty() {
            let _ = writeln!(out, "nothing abnormal detected");
        } else {
            for a in &anomalies {
                let _ = writeln!(
                    out,
                    "  [{}] {}{}",
                    if a.severity == "warning" { "PROBABLY ABNORMAL" } else { "review" },
                    if a.subject.is_empty() { String::new() } else { format!("{}: ", a.subject) },
                    a.detail
                );
            }
        }
    }
    out
}

