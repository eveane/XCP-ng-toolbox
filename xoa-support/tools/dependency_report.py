#!/usr/bin/env python3
"""dependency_report.py — tracked dependency inventory for xoa-support.

Security requirement #8: every dependency and external tool must be
tracked so new CVEs can be mapped to our exposure quickly.

This script emits docs/DEPENDENCIES.md (committed, reviewable in PRs) from:
  - requirements.txt / requirements-dev.txt (Python deps, pinned when used)
  - tools/external_tools.txt (OS-level tools invoked at runtime, with the
    package that provides them on Debian/XOA)
  - upstream projects we integrate with or follow rules from
    (xen-orchestra, sosreport) — tracked for license/rule changes.

Run:  python3 tools/dependency_report.py
CI re-runs it and fails if the committed DEPENDENCIES.md is stale.
For vulnerability scanning of Python deps, CI runs `pip-audit` against
requirements-dev.txt; for OS packages, the XOA base image is covered by
XCP-ng's own update feed.

License: GPL-2.0-only.
"""

import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

UPSTREAM = [
    ("vatesfr/xen-orchestra", "https://github.com/vatesfr/xen-orchestra",
     "AGPL-3.0 (packages) / ISC (some libs) — we follow its rules; we do NOT copy code"),
    ("sosreport/sos", "https://github.com/sosreport/sos",
     "GPL-2.0 — our sos plugin is written to its plugin API and licensed GPL-2.0-only"),
    ("eveane/XCP-ng-toolbox", "https://github.com/eveane/XCP-ng-toolbox",
     "this repository — base rules for the project"),
]


def read_lines(relpath):
    path = os.path.join(ROOT, relpath)
    if not os.path.exists(path):
        return []
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out


def main():
    py = read_lines("requirements.txt")
    py_dev = read_lines("requirements-dev.txt")
    tools = read_lines("tools/external_tools.txt")
    lines = [
        "# Dependency inventory (generated — do not hand-edit)",
        "",
        "Generated by `tools/dependency_report.py`. Re-run it and commit the",
        "result whenever requirements or external tools change. CI fails if",
        "this file is stale.",
        "",
        "## Python runtime dependencies",
        "",
    ]
    lines += [f"- `{d}` (none = stdlib-only, nothing to audit)" for d in py] or [
        "- none (stdlib only)"
    ]
    lines += ["", "## Python dev/test dependencies", ""]
    lines += [f"- `{d}`" for d in py_dev] or ["- none"]
    lines += [
        "",
        "Scanned for known vulnerabilities in CI with `pip-audit`",
        "(see `.github/workflows/xoa-support-ci.yml`).",
        "",
        "## External OS tools used at runtime (provided by the XOA base image)",
        "",
    ]
    lines += [f"- {t}" for t in tools] or ["- none"]
    lines += [
        "",
        "OS packages come from the XOA/Debian base image and are covered by the",
        "XCP-ng update feed; xoa-support itself ships no binaries.",
        "",
        "## Upstream projects tracked for rules/license/security changes",
        "",
        "| project | url | why tracked |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {u} | {w} |" for n, u, w in UPSTREAM]
    lines += ["", "Tracked via GitHub Dependabot (`/.github/dependabot.yml`)",
              "and release-watching; see docs/DEPENDENCY-SECURITY.md.", ""]
    out = os.path.join(ROOT, "docs", "DEPENDENCIES.md")
    content = "\n".join(lines)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
